import {strict as assert} from 'node:assert';
import {summarize,periodRange,defaultBudget,debtSummary,debtDue,budgetAlerts,budgetChart} from '../lib/finance.ts';
const b=defaultBudget('2026-09');b.expected=5000000;b.pockets=[{id:'kos',name:'Kos',kind:'required',amount:1500000},{id:'save',name:'Darurat',kind:'saving',amount:1000000},{id:'daily',name:'Harian',kind:'daily',amount:2500000}];
const tx=(id,type,amount,pocket='')=>({id,period:'2026-09',date:'2026-09-25',type,amount,pocket,note:id});
assert.equal(summarize(b,[],'2026-09-25').spendable,0,'Planned salary is not cash');
const income=tx('gaji','income',5000000);assert.equal(summarize(b,[income],'2026-09-25').spendable,2500000);
assert.equal(summarize(b,[income,tx('rent','expense',1500000,'kos')],'2026-09-25').spendable,2500000,'Paying required cost does not reserve it twice');
assert.equal(summarize(b,[income,tx('save','expense',1000000,'save')],'2026-09-25').spendable,2500000,'Savings transfer releases same reservation');
assert.equal(summarize(b,[income,tx('eat','expense',100000,'daily')],'2026-09-25').spendable,2400000);
assert.equal(summarize(b,[income,tx('rent','expense',2000000,'kos')],'2026-09-25').spendable,2000000,'Overrun reduces free cash');
assert.equal(summarize(b,[income,tx('eat','expense',7000000,'daily')],'2026-09-25').daily,83333);
assert.deepEqual(periodRange('2026-01',31),{start:'2026-01-31',end:'2026-02-27',next:'2026-02-28'});
assert.equal(periodRange('2028-02',31).start,'2028-02-29');
assert.equal(summarize(b,[income],'2026-10-24').days,1);
assert.equal(summarize(b,[income],'2026-10-25').daily,83333);
assert.equal(summarize(b,[income],'2026-09-25').days,30);
assert.equal(summarize(b,[],'2026-10-24').daily,83333,'Allowance is the planned allocation divided by full payday period');
assert.equal(summarize({...b,period:'2028-02',payday:1},[]).periodDays,29);
const debt={id:'test',name:'Laptop',total:1000000,term:3,startPeriod:'2026-08',paidInstallments:1};
assert.equal(debtSummary(debt).remaining,666667);
assert.equal(debtDue(debt,'2026-08'),0);
assert.equal(debtDue(debt,'2026-09'),333333);
assert.equal(debtDue({...debt,paid:333333},'2026-10'),333334);
assert.equal(debtSummary({...debt,paid:666667}).remaining,0);
assert.equal(budgetAlerts(b,[tx('e','expense',2000000,'daily')],'2026-09-26').find(a=>a.key==='pocket:daily').level,'warning');
assert.equal(budgetAlerts(b,[tx('e','expense',2500001,'daily')],'2026-09-26').find(a=>a.key==='pocket:daily').level,'danger');
const chart=budgetChart(b,[tx('e','expense',100000,'daily')],'2026-09-26');
assert.equal(chart.length,30);assert.equal(chart[1].actual,100000);assert.equal(chart[2].actual,null);
console.log('Finance checks passed: cash, payday periods, fixed allowance, debt, alerts and chart.');
